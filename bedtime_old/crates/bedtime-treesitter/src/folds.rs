// Fold structural containers and compound statements, not arbitrary multiline
// expressions. Python needs the compound statement's header, not its body block.
pub(crate) fn fold_kinds(language: &str) -> Option<&'static [&'static str]> {
    Some(match language {
        "rust" => &[
            "function_item",
            "impl_item",
            "mod_item",
            "trait_item",
            "struct_item",
            "enum_item",
            "if_expression",
            "else_clause",
            "for_expression",
            "while_expression",
            "loop_expression",
            "match_expression",
            "block",
            "declaration_list",
            "field_declaration_list",
            "enum_variant_list",
            "match_block",
            "field_initializer_list",
            "array_expression",
            "use_list",
            "block_comment",
            "raw_string_literal",
        ],
        "python" => &[
            "function_definition",
            "class_definition",
            "if_statement",
            "elif_clause",
            "else_clause",
            "for_statement",
            "while_statement",
            "with_statement",
            "try_statement",
            "except_clause",
            "finally_clause",
            "match_statement",
            "case_clause",
            "dictionary",
            "list",
            "set",
            "tuple",
            "string",
        ],
        "javascript" | "typescript" | "tsx" => &[
            "statement_block",
            "class_body",
            "switch_body",
            "enum_body",
            "interface_body",
            "object_type",
            "object",
            "array",
            "jsx_element",
            "comment",
            "template_string",
        ],
        "json" => &["object", "array", "comment"],
        "c" | "cpp" => &[
            "function_definition",
            "struct_specifier",
            "class_specifier",
            "enum_specifier",
            "namespace_definition",
            "compound_statement",
            "declaration_list",
            "field_declaration_list",
            "enumerator_list",
            "initializer_list",
            "comment",
            "raw_string_literal",
        ],
        "go" => &[
            "block",
            "field_declaration_list",
            "interface_type",
            "literal_value",
            "import_spec_list",
            "var_spec_list",
            "expression_switch_statement",
            "type_switch_statement",
            "select_statement",
            "comment",
            "raw_string_literal",
        ],
        "html" => &["element", "script_element", "style_element", "comment"],
        "css" => &["block", "keyframe_block_list", "comment"],
        "java" => &[
            "block",
            "class_body",
            "interface_body",
            "enum_body",
            "constructor_body",
            "module_body",
            "annotation_type_body",
            "array_initializer",
            "switch_block",
            "block_comment",
        ],
        "c-sharp" => &[
            "block",
            "declaration_list",
            "enum_member_declaration_list",
            "accessor_list",
            "initializer_expression",
            "switch_body",
            "switch_expression",
            "comment",
            "verbatim_string_literal",
            "raw_string_literal",
        ],
        "kotlin" => &[
            "class_body",
            "enum_class_body",
            "function_body",
            "control_structure_body",
            "when_expression",
            "multiline_comment",
            "string_literal",
        ],
        "ruby" => &[
            "class",
            "module",
            "method",
            "singleton_method",
            "singleton_class",
            "do_block",
            "block",
            "if",
            "unless",
            "while",
            "until",
            "for",
            "case",
            "case_match",
            "begin",
            "array",
            "hash",
            "heredoc_body",
            "comment",
        ],
        "bash" => &[
            "compound_statement",
            "function_definition",
            "if_statement",
            "elif_clause",
            "else_clause",
            "for_statement",
            "while_statement",
            "case_statement",
            "heredoc_body",
        ],
        "hcl" => &["block", "object", "tuple", "comment", "heredoc_template"],
        "toml" => &[
            "table",
            "table_array_element",
            "array",
            "inline_table",
            "string",
        ],
        "swift" => &[
            "class_body",
            "function_body",
            "statements",
            "multiline_comment",
        ],
        "dart" => &[
            "class_body",
            "block",
            "enum_body",
            "list_literal",
            "set_or_map_literal",
            "comment",
        ],
        "php" => &[
            "compound_statement",
            "declaration_list",
            "array_creation_expression",
            "comment",
        ],
        "lua" => &[
            "function_declaration",
            "function_definition",
            "if_statement",
            "for_statement",
            "while_statement",
            "repeat_statement",
            "table_constructor",
            "comment",
        ],
        "powershell" => &[
            "statement_block",
            "script_block",
            "class_statement",
            "function_statement",
            "comment",
        ],
        "yaml" => &[
            "block_mapping_pair",
            "block_sequence_item",
            "flow_mapping",
            "flow_sequence",
            "block_scalar",
        ],
        "xml" => &["element", "Comment", "CDSect"],
        "markdown" => &["section", "fenced_code_block", "list", "block_quote"],
        "sql" => &[
            "statement",
            "block",
            "create_table",
            "create_function",
            "comment",
        ],
        "dockerfile" => &["run_instruction", "heredoc_block"],
        "cmake" => &[
            "function_def",
            "macro_def",
            "if_condition",
            "foreach_loop",
            "while_loop",
            "bracket_comment",
        ],
        "make" => &["rule", "define_directive", "conditional"],
        _ => return None,
    })
}
